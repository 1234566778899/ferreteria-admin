create view public.product_stock with (security_invoker = true) as
select p.*,
       c.name as category_name, c.color as category_color, s.name as supplier_name,
       round(p.stock * p.cost, 2) as value_cost,
       round(p.stock * p.price, 2) as value_price,
       case when p.price > 0 then round((1 - p.cost / p.price) * 100, 1) end as margin,
       (p.stock <= 0) as is_out,
       (p.stock > 0 and p.stock <= p.min_stock) as is_low,
       m.last_entry_at, m.last_exit_at
from public.product p
left join public.category c on c.id = p.category_id
left join public.supplier s on s.id = p.supplier_id
left join lateral (
  select max(created_at) filter (where quantity > 0) as last_entry_at,
         max(created_at) filter (where quantity < 0) as last_exit_at
  from public.stock_movement where product_id = p.id
) m on true;

-- Listas con nombre del usuario (corren como dueño para leer staff; filtran por personal activo).
create view public.doc_list as
select d.*, su.name as supplier_name, nullif(concat_ws(' ', st.first_name, st.last_name), '') as user_name
from public.stock_doc d
left join public.supplier su on su.id = d.supplier_id
left join public.staff st on st.user_id = d.user_id
where internal.is_staff();

create view public.movement_list as
select m.*, d.number as doc_number, d.kind, d.reason, d.reference, d.party, d.voided_at, d.user_id,
       p.code, p.name as product_name, p.brand, p.model, p.unit,
       nullif(concat_ws(' ', st.first_name, st.last_name), '') as user_name
from public.stock_movement m
join public.stock_doc d on d.id = m.doc_id
join public.product p on p.id = m.product_id
left join public.staff st on st.user_id = d.user_id
where internal.is_staff();

create or replace function public.inv_doc(p_doc uuid) returns jsonb
language plpgsql stable security definer set search_path = public as $$
begin
  perform internal.assert_staff();
  return (select to_jsonb(d) || jsonb_build_object(
    'lines', (select coalesce(jsonb_agg(to_jsonb(m) || jsonb_build_object('code', p.code, 'product_name', p.name, 'brand', p.brand, 'model', p.model, 'unit', p.unit)
                                        order by p.name), '[]')
              from public.stock_movement m join public.product p on p.id = m.product_id where m.doc_id = d.id))
    from public.doc_list d where d.id = p_doc);
end $$;
